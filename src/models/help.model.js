import mongoose from "mongoose";

const { Schema, model } = mongoose;

const helpSchema = new Schema(
  {
    question: {
      type: String,
      required: true,
      trim: true,
    },
    answer: {
      type: String,
      required: true,
      trim: true,
    },
    status: {
      type: String,
      enum: ["active", "inactive"],
      default: "active",
    },
  },
  { timestamps: true, versionKey: false },
);

const Help = model("Help", helpSchema);

export default Help;
